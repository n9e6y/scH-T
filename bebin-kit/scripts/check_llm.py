"""Probe the OpenAI-compatible LLM provider and write docs/LLM_CAPABILITIES.md (ARCHITECTURE §11.2).

Reads LLM_BASE_URL / LLM_API_KEY from .env. Run: make check-llm
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))

from openai import OpenAI  # noqa: E402

from app.config import get_settings  # noqa: E402

OUT = ROOT / "docs" / "LLM_CAPABILITIES.md"
PREFERRED = ["gpt-4.1", "gpt-4o", "gpt-4.1-mini", "gpt-4o-mini", "gpt-4.1-nano"]


def timed(fn):
    t0 = time.perf_counter()
    try:
        return True, fn(), int((time.perf_counter() - t0) * 1000)
    except Exception as e:  # noqa: BLE001 - we want to record any provider failure
        return False, f"{type(e).__name__}: {str(e)[:160]}", int((time.perf_counter() - t0) * 1000)


def main():
    s = get_settings()
    if not (s.llm_base_url and s.llm_api_key):
        sys.exit("Set LLM_BASE_URL and LLM_API_KEY in .env first.")
    client = OpenAI(base_url=s.llm_base_url, api_key=s.llm_api_key, timeout=30)
    ok, models, _ = timed(lambda: [m.id for m in client.models.list().data])
    models = models if ok else []
    model = s.llm_model_assistant or next((m for m in PREFERRED if m in models), models[0] if models else "gpt-4o-mini")
    fast = s.llm_model_fast or next((m for m in reversed(PREFERRED) if m in models), model)
    rows = []

    def chat():
        r = client.chat.completions.create(model=model, messages=[{"role": "user", "content": "Say OK"}], max_tokens=5)
        return r.choices[0].message.content

    def stream():
        chunks = list(client.chat.completions.create(model=model, stream=True, max_tokens=20,
                                                     messages=[{"role": "user", "content": "Count to 5"}]))
        return f"{len(chunks)} chunks"

    def tools():
        r = client.chat.completions.create(
            model=model, messages=[{"role": "user", "content": "What's the weather in Tehran?"}],
            tools=[{"type": "function", "function": {"name": "get_weather", "parameters": {
                "type": "object", "properties": {"city": {"type": "string"}}, "required": ["city"]}}}])
        calls = r.choices[0].message.tool_calls
        assert calls, "no tool call returned"
        return calls[0].function.arguments

    def json_mode():
        r = client.chat.completions.create(model=model, response_format={"type": "json_object"},
                                           messages=[{"role": "user", "content": 'Return JSON {"ok": true}'}])
        return json.loads(r.choices[0].message.content)

    def emb(dims):
        kw = {"dimensions": dims} if dims else {}
        r = client.embeddings.create(model=s.embeddings_model or "text-embedding-3-small", input=["گوشی"], **kw)
        return f"dim={len(r.data[0].embedding)}"

    def persian():
        r = client.chat.completions.create(model=fast, max_tokens=80, messages=[{"role": "user", "content":
            "مثل یک فروشنده‌ی مؤدب در تهران، در یک جمله بگو سایز ۴۳ موجود است و قیمت امروز ۳ میلیون و ۷۰۰ است."}])
        return r.choices[0].message.content

    for name, fn in [("chat", chat), ("streaming", stream), ("tool calling", tools), ("JSON mode", json_mode),
                     ("embeddings", lambda: emb(None)), ("embeddings + dimensions=256", lambda: emb(256)),
                     ("Persian (fast model)", persian)]:
        ok, out, ms = timed(fn)
        rows.append((name, ok, out, ms))
        print(f"{'PASS' if ok else 'FAIL'} {name} ({ms} ms): {out}")

    passed = {n: ok for n, ok, _, _ in rows}
    emb_rec = "api" if passed.get("embeddings") else "off"
    lines = ["# LLM capabilities", "", f"Generated by `scripts/check_llm.py` on {time.strftime('%Y-%m-%d %H:%M')}.", "",
             f"Provider: `{s.llm_base_url}` · models listed: {len(models)}", "",
             "| Check | Result | Latency | Output |", "|---|---|---|---|"]
    lines += [f"| {n} | {'✅' if ok else '❌'} | {ms} ms | {str(out).replace('|', '/')[:120]} |" for n, ok, out, ms in rows]
    lines += ["", "## Recommendation", f"- `LLM_MODEL_ASSISTANT={model}`", f"- `LLM_MODEL_FAST={fast}`",
              f"- `EMBEDDINGS_PROVIDER={emb_rec}`",
              f"- Assistant mode: {'tool calling' if passed.get('tool calling') else 'JSON intent router (no tools)'}",
              "", "## Models", ", ".join(models[:60]) or "(not listed)"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
