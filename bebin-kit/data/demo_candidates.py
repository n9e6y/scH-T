"""Pick demo scenarios from catalog.db and write docs/DEMO_CANDIDATES.md (MILESTONES M1)."""
from __future__ import annotations

import json
import sqlite3
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "api"))
from app.hours import TEHRAN, open_status  # noqa: E402

DB = ROOT / "api" / "data" / "catalog.db"
OUT = ROOT / "docs" / "DEMO_CANDIDATES.md"
RADIUS_KM = 5


def hav_km(a, b, c, d):
    from math import asin, cos, radians, sin, sqrt
    p1, p2 = radians(a), radians(c)
    x = sin((p2 - p1) / 2) ** 2 + cos(p1) * cos(p2) * sin(radians(d - b) / 2) ** 2
    return 2 * 6371 * asin(sqrt(x))


def main():
    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    snap = datetime.fromisoformat(con.execute("SELECT value FROM meta WHERE key='snapshot_date'").fetchone()[0])
    areas = [dict(r) for r in con.execute("SELECT * FROM areas ORDER BY shop_count DESC")]
    # A weekday evening for the "closes in the evening" check: Wednesday 17:40 Tehran.
    probe = datetime(2026, 10, 21, 17, 40, tzinfo=TEHRAN)
    cands = con.execute("""
        SELECT p.* FROM products p WHERE p.offer_count >= 4
          AND p.category_group IN ('mobile','audio','laptop','watch','fashion','appliances','beauty')
        ORDER BY p.offer_count DESC LIMIT 400""").fetchall()
    scenarios = []
    for p in cands:
        rows = [dict(r) for r in con.execute("""
            SELECT o.price_toman, o.price_outlier, o.last_price_changed_at, o.warranty_months, s.*
            FROM offers o JOIN shops s USING(shop_id) WHERE o.product_id=?""", (p["product_id"],))]
        best = None
        for a in areas[:6]:
            near = [r for r in rows if hav_km(a["lat"], a["lng"], r["lat"], r["lng"]) <= RADIUS_KM
                    and r["price_toman"] and not r["price_outlier"]]
            if len(near) < 3:
                continue
            ages = [(snap - datetime.fromisoformat(r["last_price_changed_at"])).days
                    for r in near if r["last_price_changed_at"]]
            evening = []
            for r in near:
                if r["hours_json"]:
                    wk = {int(k): v for k, v in json.loads(r["hours_json"]).items()}
                    st = open_status(wk, probe)
                    if st.state in ("open", "closing_soon") and st.closes_at and "17:00" <= st.closes_at <= "21:30":
                        evening.append(r)
            checks = {
                "installments": any(r["installments"] == 1 for r in near),
                "torob_pay": any(r["torob_pay"] == 1 for r in near),
                "mall_floor_unit": any(r["mall_id"] and r["floor_order"] is not None and r["unit"] for r in near),
                "stale_price": any(x > 14 for x in ages),
                "fresh_price": any(x <= 3 for x in ages),
                "evening_close": bool(evening),
                "unknown_hours": any(not r["hours_known"] for r in near),
                "real_name": any(r["is_real_name"] for r in near),
            }
            score = sum(checks.values()) + min(len(near), 10) / 10
            if not best or score > best["score"]:
                best = {"score": score, "area": a["name_fa"], "near": near, "checks": checks}
        if best and all(best["checks"][k] for k in ("installments", "mall_floor_unit", "stale_price", "evening_close")):
            scenarios.append((p, best))
    scenarios.sort(key=lambda s: -s[1]["score"])
    seen_groups, picked = {}, []
    for p, b in scenarios:
        if seen_groups.get(p["category_group"], 0) >= 2:
            continue
        seen_groups[p["category_group"]] = seen_groups.get(p["category_group"], 0) + 1
        picked.append((p, b))
        if len(picked) == 5:
            break

    real = [dict(r) for r in con.execute("""SELECT shop_id, name, instagram, website, area, offer_count
        FROM shops WHERE is_real_name=1 AND offer_count>0 ORDER BY offer_count DESC LIMIT 6""")]

    L = ["# Demo candidates", "",
         f"Generated by `data/demo_candidates.py` from catalog.db (snapshot {snap.date()}). Re-run after every rebuild.", "",
         "**Reality check:** the dataset is concentrated in downtown Tehran's electronics/electrical bazaar "
         "(فردوسی، شیخ هادی، بهارستان ≈ 85% of shops). There are no shops within 2 km of ونک, and running shoes are rare. "
         "The design sample data (Pegasus 41 near ونک) is illustrative only; the demo video should use one of these.", "",
         "Evening-close check uses Wednesday 17:40 Tehran (the design's sample «now»).", ""]
    for i, (p, b) in enumerate(picked, 1):
        near = sorted(b["near"], key=lambda r: r["price_toman"])
        L += [f"## {i}. {p['title_fa']}", "",
              f"- product_id: `{p['product_id']}` · category: {p['category']} · group: {p['category_group']}",
              f"- area preset: **{b['area']}** · listed sellers within {RADIUS_KM} km: **{len(near)}** "
              f"(of {p['offer_count']} total)",
              "- checks: " + ", ".join(f"{k} {'✓' if v else '✗'}" for k, v in b["checks"].items()),
              "", "| shop | mall / floor / unit | price | changed | inst | hours |", "|---|---|---|---|---|---|"]
        for r in near[:8]:
            loc = " / ".join(filter(None, [r["mall_name"], r["floor_label"], r["unit"]])) or "—"
            L.append(f"| {r['name']} `{r['shop_id']}` | {loc} | {r['price_toman']:,} | "
                     f"{(r['last_price_changed_at'] or '')[:10]} | {r['installments'] if r['installments'] is not None else '?'} | "
                     f"{'known' if r['hours_known'] else 'unknown'} |")
        sim = con.execute("""SELECT title_fa, offer_count, min_price FROM products
            WHERE category=? AND product_id<>? AND offer_count>=2 ORDER BY offer_count DESC LIMIT 3""",
                          (p["category"], p["product_id"])).fetchall()
        L += ["", "Similar products (same category, ≥2 sellers): " +
              "; ".join(f"{s['title_fa']} ({s['offer_count']} sellers)" for s in sim), ""]
    L += ["## Real-name shops (Instagram / website)", "", "| shop | link | area | offers |", "|---|---|---|---|"]
    for r in real:
        L.append(f"| {r['name']} `{r['shop_id']}` | {r['instagram'] or r['website']} | {r['area']} | {r['offer_count']} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)  # docs/ isn't in git; a fresh clone lacks it
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(picked)} scenarios")


if __name__ == "__main__":
    main()
