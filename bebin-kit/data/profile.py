"""Profile the raw CSVs → docs/DATA_PROFILE.md (generated; DATA_CONTRACT.md is the curated version)."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "DATA_PROFILE.md"
EMPTY = {"", "null", "[]", "{}"}


def fmt(fmtname: str, s: pd.Series) -> str:
    probe = s[~s.isin(EMPTY)].head(200)
    ok = 0
    for v in probe:
        try:
            json.loads(v)
            ok += 1
        except ValueError:
            pass
    if len(probe) and ok == len(probe) and probe.str.startswith(("[", "{")).all():
        return "JSON"
    return fmtname


def main():
    lines = ["# Raw data profile (generated by `data/profile.py`)", ""]
    for name in ["shops", "products", "offers"]:
        path = RAW / f"{name}.csv"
        df = pd.read_csv(path, dtype=str, keep_default_na=False)
        lines += [f"## {name}.csv", "", f"{len(df):,} rows · {path.stat().st_size / 1e6:.1f} MB · UTF-8, RFC4180 quoting", "",
                  "| column | empty/null % | distinct | format | examples |", "|---|---|---|---|---|"]
        for c in df.columns:
            s = df[c]
            empty = s.isin(EMPTY)
            ex = " · ".join(v[:60].replace("|", "/").replace("\n", " ") for v in s[~empty].drop_duplicates().head(3))
            lines.append(f"| {c} | {empty.mean():.1%} | {s.nunique():,} | {fmt('text', s)} | {ex} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)  # docs/ isn't in git; a fresh clone lacks it
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
